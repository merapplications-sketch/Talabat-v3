const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const path = require('node:path');
const root = path.join(__dirname, '..', 'dist');
const core = fs.readFileSync(path.join(root, 'talabat-core.js'), 'utf8');
const page = fs.readFileSync(path.join(root, 'customer.html'), 'utf8');
const shape = core.slice(core.indexOf('  function shape()'), core.indexOf('  /* sound + toast'));
const receipt = page.slice(page.indexOf('const isCash='), page.indexOf('const rcStatus='));
const ctx = vm.createContext({DB:{orders:[],oitems:[],recipients:{},approvals:{},contacts:{},chat:[]},storeName:()=>'',storePhone:()=>'',TLB:{wallet:()=>({})},S:{owl:42,ow:[{kind:'return',amount:20}]},t:k=>k,fmtN:String});
vm.runInContext(shape + '\n' + receipt, ctx);
const raw = {id:42,status:'cancelled',wallet_used:20,total:40,payment:'cash',wallet_returned_at:'2026-01-01T00:00:00Z',points_used:1000,points_returned_at:'2026-01-01T00:00:00Z'};
ctx.DB.orders=[raw];
const html=vm.runInContext('settleCard(shape()[0])',ctx);
assert.match(html,/stlWal<\/span><span[^>]*>\+20 TJS/,'recorded wallet return must be confirmed in receipt');
assert.match(html,/stlPts<\/span><span[^>]*>\+1000/,'recorded point return must be confirmed');
ctx.DB.orders=[{...raw,wallet_returned_at:null,points_returned_at:null}];
assert.match(vm.runInContext('settleCard(shape()[0])',ctx),/stlWalU/,'missing return evidence must stay unconfirmed');
assert.match(vm.runInContext('settleCard(shape()[0])',ctx),/stlPtsU/);
console.log('return receipt: confirmed and missing evidence passed');
